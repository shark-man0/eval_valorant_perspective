"""Print the 44-rule temporal / aggregation policy table (Markdown) from the rules JSON.

Read-only: it only formats what ``TemporalPolicyTable`` loaded. The table in
``docs/temporal_policy_contract_audit.md`` is generated by this script, and a unit test
fails when the two drift apart.

    python scripts/audit_temporal_policy.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

from valorant_ai_coach.rules.temporal_contract import (  # noqa: E402
    RuleTemporalPolicy,
    TemporalPolicyTable,
)

HEADER = (
    "| Rule | Level | event_window (前/後 秒) | requires_round_timeline "
    "| requires_previous_round_context | uses_whole_match_aggregation | display_clip_strategy "
    "| automation (candidate_selection / final_label_mode) "
    "| aggregation (反復集約 / 重複排除秒 / 表示上限 / 要約閾値) |"
)
DIVIDER = "|" + "---|" * 9


def _flag(value: bool) -> str:
    return "yes" if value else "no"


def render_row(policy: RuleTemporalPolicy) -> str:
    window = (
        "-"
        if policy.event_window is None
        else f"{policy.event_window.before_sec:g}/{policy.event_window.after_sec:g}"
    )
    summary = (
        "-"
        if policy.summary_required_if_occurrences_at_least is None
        else str(policy.summary_required_if_occurrences_at_least)
    )
    cells = [
        policy.rule_id,
        policy.level,
        window,
        _flag(policy.requires_round_timeline),
        _flag(policy.requires_previous_round_context),
        _flag(policy.uses_whole_match_aggregation),
        policy.display_clip_strategy,
        f"{policy.candidate_selection} / {policy.final_label_mode}",
        f"{_flag(policy.aggregate_repeated_occurrences)} / "
        f"{policy.deduplicate_same_rule_within_seconds:g} / "
        f"{policy.max_display_exemplars_per_match} / {summary}",
    ]
    return "| " + " | ".join(cells) + " |"


def render_rule_table(table: TemporalPolicyTable | None = None) -> str:
    table = table or TemporalPolicyTable.load()
    return "\n".join([HEADER, DIVIDER, *(render_row(policy) for policy in table)])


def main() -> int:
    print(render_rule_table())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
